"""The words a passphrase is made from.

Nothing here decides who owns the machine — `frase.py` does that. This
module is only the raw material: at least 512 ordinary Spanish words, so
that four of them, drawn with `secrets.choice`, give at least 36 bits.
512 is a floor, not a target; there are 694.

**Four rules chose every word:**

1. **Nothing a person would have to spell.** Concrete, everyday nouns
   and adjectives — the kind in a children's book, not a dictionary of
   rare usage.
2. **No near-homophones, in either direction.** Not "vaca"/"baca", not
   "hola"/"ola", not "haya"/"aya"/"halla", not "casa"/"caza". Spanish b
   and v are the same sound, so a b/v minimal pair is a true homophone,
   not a spelling quirk — and this house speaks Peninsular Spanish,
   which does distinguish "casa" from "caza" (seseo does not), but the
   pair was left out anyway: excluding it costs nothing and a collision
   costs a passphrase that will not match.
3. **Nothing whose accent changes the word.** Not "papa"/"papá", not
   "esta"/"está". Rather than police every such pair by hand, no word
   here carries a written accent or dieresis at all — every word is
   plain lowercase ASCII, with "ñ" as the one addition, because "ñ" is
   its own letter, not a diacritic on "n" (`unicodedata.normalize` does
   not decompose it under NFC, only under a deliberate NFD that then
   also strips it, which nothing here does). Two real words that
   otherwise needed a dieresis to be pronounced correctly — "pingüino",
   "cigüeña" — are simply not on the list, rather than written wrong.
4. **Nothing that could be heard as an instruction, and nothing coarse.**
   Somebody reads this off a screen, possibly in front of their
   children.

Built with a script, not by hand: candidate words were screened by
folding away the b/v, s/z/c, g/j and silent-h distinctions Spanish
pronunciation does not make, and any two candidates that folded to the
same sound were both dropped rather than one kept — the ambiguity was
the reason to write the screen in the first place, and it is safer to
lose a good word than to keep a bad pair.
"""

